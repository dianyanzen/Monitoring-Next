-- Run only after reviewing PDAK_METADATA.sql on monalisa_db.
-- Explicitly select one authorized staff level; never grant all signed-in users.
ACCEPT PDAK_USER_LEVEL NUMBER PROMPT 'Authorized PDAK uploader USER_LEVEL: '
DECLARE
  v_level NUMBER := &PDAK_USER_LEVEL;
  v_id NUMBER;
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='SIAK_MENU' AND COLUMN_NAME IN
    ('MENU_ID','PARENT_ID','TITLE','URL','ICON','MENU_LEVEL','LEVEL_HEAD','LEVEL_SUB','LEVEL_CONTENT','IS_NEXT','IS_ACTIVE','IS_BLANK');
  IF n<>12 THEN RAISE_APPLICATION_ERROR(-20010,'Menu metadata differs; adapt seed before running'); END IF;
  SELECT COUNT(*) INTO n FROM SIAK_USER_LEVEL WHERE USER_LEVEL=v_level;
  IF n<>1 THEN RAISE_APPLICATION_ERROR(-20011,'User level is not valid'); END IF;
  LOCK TABLE SIAK_MENU IN SHARE ROW EXCLUSIVE MODE;
  SELECT MIN(MENU_ID),COUNT(*) INTO v_id,n FROM SIAK_MENU WHERE LOWER(TRIM(BOTH '/' FROM TRIM(URL)))='pdak/upload';
  IF n>1 THEN RAISE_APPLICATION_ERROR(-20012,'Duplicate PDAK menu URLs require reconciliation'); END IF;
  IF n=0 THEN
    SELECT NVL(MAX(MENU_ID),0)+1 INTO v_id FROM SIAK_MENU;
    INSERT INTO SIAK_MENU (MENU_ID,PARENT_ID,TITLE,URL,ICON,MENU_LEVEL,LEVEL_HEAD,LEVEL_SUB,LEVEL_CONTENT,IS_NEXT,IS_ACTIVE,IS_BLANK)
    VALUES(v_id,0,'Upload Data PDAK','/pdak/upload','mdi mdi-upload',1,90,0,0,1,1,0);
  END IF;
  MERGE INTO SIAK_AKSES A USING (SELECT v_level AS USER_LEVEL,v_id AS MENU_ID FROM DUAL) B
  ON (A.USER_LEVEL=B.USER_LEVEL AND A.MENU_ID=B.MENU_ID)
  WHEN MATCHED THEN UPDATE SET A.IS_ACTIVE=1
  WHEN NOT MATCHED THEN INSERT(USER_LEVEL,MENU_ID,IS_ACTIVE) VALUES(B.USER_LEVEL,B.MENU_ID,1);
END;
/
COMMIT;
