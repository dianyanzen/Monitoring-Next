-- Oracle 12.2; normal MONALISA / monalisa_db connection, application alias DB.
-- Existing production batch schema was audited on 2026-10-13. No ALTER of it.
-- Execute as a separate DBA-reviewed migration, never from an HTTP request.
DECLARE n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='PDAK_UPLOAD_BATCH';
  IF n=0 THEN
    EXECUTE IMMEDIATE 'CREATE TABLE PDAK_UPLOAD_BATCH (
      ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      DATASET_TYPE VARCHAR2(40 CHAR) NOT NULL,
      TANGGAL_ENTRY DATE NOT NULL, STATUS VARCHAR2(20 CHAR) DEFAULT ''COMMITTED'' NOT NULL,
      SOURCE_FILE VARCHAR2(200 CHAR), UPLOADED_BY VARCHAR2(128 CHAR),
      UPLOADED_AT TIMESTAMP(6) DEFAULT SYSTIMESTAMP,
      TOTAL_ROWS NUMBER, INSERTED_ROWS NUMBER,
      ERROR_CODE VARCHAR2(100 CHAR), ERROR_MESSAGE VARCHAR2(1000 CHAR), FILE_SHA256 VARCHAR2(64 CHAR),
      CONSTRAINT UK_PDAK_UPLOAD_BATCH UNIQUE(DATASET_TYPE,TANGGAL_ENTRY),
      CONSTRAINT CK_PDAK_BATCH_TANGGAL CHECK(TANGGAL_ENTRY=TRUNC(TANGGAL_ENTRY)),
      CONSTRAINT CK_PDAK_BATCH_DATASET CHECK(DATASET_TYPE IN (''KIA'',''AKTA_KELAHIRAN'',''PEREKAMAN_KTPL'',''IKD'')),
      CONSTRAINT CK_PDAK_BATCH_STATUS CHECK(STATUS=''COMMITTED'')
    )';
  ELSE
    SELECT COUNT(*) INTO n FROM USER_TAB_COLUMNS WHERE TABLE_NAME='PDAK_UPLOAD_BATCH' AND COLUMN_NAME IN
      ('ID','DATASET_TYPE','TANGGAL_ENTRY','STATUS','SOURCE_FILE','UPLOADED_BY','UPLOADED_AT','TOTAL_ROWS','INSERTED_ROWS','ERROR_CODE','ERROR_MESSAGE','FILE_SHA256');
    IF n<>12 THEN RAISE_APPLICATION_ERROR(-20001,'Existing batch schema differs; review metadata'); END IF;
  END IF;
END;
/

-- Optional dedicated attempt history. Without this table, failures are still in Log.
-- It has no daily unique slot, so a failed upload can be retried.
DECLARE n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME='PDAK_UPLOAD_ATTEMPT';
  IF n=0 THEN EXECUTE IMMEDIATE 'CREATE TABLE PDAK_UPLOAD_ATTEMPT (
    ID VARCHAR2(32 CHAR) DEFAULT RAWTOHEX(SYS_GUID()) PRIMARY KEY,
    DATASET_TYPE VARCHAR2(40 CHAR), TANGGAL_ENTRY DATE NOT NULL, STATUS VARCHAR2(40 CHAR) NOT NULL,
    UPLOADED_BY VARCHAR2(128 CHAR) NOT NULL, SOURCE_FILE VARCHAR2(200 CHAR),
    UPLOADED_AT TIMESTAMP(6) NOT NULL, ERROR_CODE VARCHAR2(40 CHAR), ERROR_MESSAGE VARCHAR2(300 CHAR),
    CONSTRAINT CK_PDAK_ATTEMPT_DATE CHECK(TANGGAL_ENTRY=TRUNC(TANGGAL_ENTRY))
  )'; END IF;
END;
/
