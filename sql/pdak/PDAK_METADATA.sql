SELECT TABLE_NAME,COLUMN_NAME,DATA_TYPE,CHAR_LENGTH,DATA_PRECISION,DATA_SCALE,NULLABLE
FROM USER_TAB_COLUMNS WHERE TABLE_NAME LIKE 'PDAK%' ORDER BY TABLE_NAME,COLUMN_ID;
SELECT TABLE_NAME,CONSTRAINT_NAME,CONSTRAINT_TYPE,STATUS,VALIDATED,SEARCH_CONDITION_VC
FROM USER_CONSTRAINTS WHERE TABLE_NAME LIKE 'PDAK%' ORDER BY TABLE_NAME,CONSTRAINT_NAME;
SELECT C.TABLE_NAME,C.CONSTRAINT_NAME,CC.COLUMN_NAME,CC.POSITION
FROM USER_CONSTRAINTS C JOIN USER_CONS_COLUMNS CC ON CC.CONSTRAINT_NAME=C.CONSTRAINT_NAME
WHERE C.TABLE_NAME LIKE 'PDAK%' AND C.CONSTRAINT_TYPE IN ('P','U') ORDER BY C.TABLE_NAME,C.CONSTRAINT_NAME,CC.POSITION;
