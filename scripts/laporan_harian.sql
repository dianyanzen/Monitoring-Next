-- Laporan Harian (range tanggal)
-- Gunakan parameter tanggal awal/akhir (format DD-MM-YYYY) untuk mengganti seluruh TRUNC(SYSDATE).
-- :p_start => tanggal mulai (wajib)
-- :p_end   => tanggal selesai (wajib)

-- REKAPITULASI PELAYANAN
WITH param AS (
  SELECT TRUNC(TO_DATE(:p_start, 'DD-MM-YYYY')) AS tgl_start,
         TRUNC(TO_DATE(:p_end,   'DD-MM-YYYY')) AS tgl_end
  FROM DUAL
)
SELECT
  A.NO,
  A.DESCRIP,
  CASE
    WHEN A.DESCRIP = 'PENCETAKAN KTP-EL' THEN
      NVL(B.VAL, 0) +
      NVL((
        SELECT SUM(D.AMBIL - D.RUSAK - D.PENGEMBALIAN)
        FROM SIAK_MONEV_BLANGKO_LUDO D, param P
        WHERE TRUNC(D.TANGGAL) BETWEEN P.tgl_start AND P.tgl_end
      ), 0)
    ELSE NVL(B.VAL, 0)
  END AS VAL
FROM SIAK_MASTER_DASHBOARD A
LEFT JOIN (
  SELECT B.DESCRIP, C.ID, SUM(C.VAL) AS VAL
  FROM SIAK_MASTER_DASHBOARD B
  INNER JOIN SIAK_DASHBOARD C ON B.VAL = C.ID
  CROSS JOIN param P
  WHERE TRUNC(C.CREATED_DT) BETWEEN P.tgl_start AND P.tgl_end
  GROUP BY B.DESCRIP, C.ID
) B ON A.VAL = B.ID
UNION ALL
SELECT 24 AS NO, 'JUMLAH BLANKO KTPEL YANG DIBAKAR' AS DESCRIP, SUM(JUMLAH) AS VAL
FROM SIAK_BLANGKO_INVALID, param P
WHERE TRUNC(TANGGAL_MASUK) BETWEEN P.tgl_start AND P.tgl_end
UNION ALL
SELECT 25 AS NO, 'PENDUDUK RENTAN' AS DESCRIP, COUNT(1) AS VAL  FROM T7_RTN_OT_BIODATA@DB222
UNION ALL
SELECT 26 AS NO, 'PENDUDUK NON PERMANEN' AS DESCRIP, COUNT(1) AS VAL  FROM T7_NOPER_DETAIL@DB222
ORDER BY NO;


-- REKAPITULASI JUMLAH PENCETAKAN KTP-EL PER WILAYAH
WITH param AS (
  SELECT TRUNC(TO_DATE(:p_start, 'DD-MM-YYYY')) AS tgl_start,
         TRUNC(TO_DATE(:p_end,   'DD-MM-YYYY')) AS tgl_end
  FROM DUAL
)
SELECT 
    A.NO_WIL, 
    A.NAMA_WIL, 
    CASE WHEN B.JML IS NULL THEN 0 ELSE B.JML END AS JML  
FROM SIAK_KODE_WIL A 
LEFT JOIN (
    SELECT
        CASE 
            WHEN E.KODE_WIL IS NULL THEN 0 
            ELSE E.KODE_WIL 
        END AS KODE_WIL,
        COUNT(1) AS JML
    FROM CARD_MANAGEMENT@DB5CETAK A
    LEFT JOIN DEMOGRAPHICS@DB5CETAK B 
        ON A.NIK = B.NIK
    LEFT JOIN SIAK_CETAK_GOIB@YZDB D 
        ON REPLACE(
                UPPER(
                    CASE 
                        WHEN A.LAST_UPDATED_USERNAME IS NULL 
                        THEN A.CREATED_USERNAME 
                        ELSE A.LAST_UPDATED_USERNAME 
                    END
                ), 
            ' ', '') = UPPER(D.USER_BCARD)
        AND D.IS_ACTIVE = 1
    LEFT JOIN SIAK_USER_EKTP E 
        ON REPLACE(
                UPPER(
                    CASE 
                        WHEN A.LAST_UPDATED_USERNAME IS NULL 
                        THEN A.CREATED_USERNAME 
                        ELSE A.LAST_UPDATED_USERNAME 
                    END
                ), 
            ' ', '') = UPPER(E.USER_ID)
    CROSS JOIN param P
    WHERE 1=1 
      AND D.USER_BCARD IS NULL
      AND E.KATEGORI = 2
      AND TRUNC(COALESCE(A.LAST_UPDATE, A.PERSONALIZED_DATE)) BETWEEN P.tgl_start AND P.tgl_end
    GROUP BY E.KODE_WIL 
    ORDER BY E.KODE_WIL
) B 
ON A.NO_WIL = B.KODE_WIL;


