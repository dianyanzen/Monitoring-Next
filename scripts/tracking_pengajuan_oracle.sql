-- Schema dan seed awal modul Tracking Pengajuan Monalisa.
-- Jalankan pada schema Oracle yang dipakai DB_ALIAS_TRACKING.

CREATE TABLE M_TRACKING_LOCATION (
  LOCATION_ID NUMBER(2) NOT NULL,
  LOCATION_CODE VARCHAR2(2) NOT NULL,
  LOCATION_NAME VARCHAR2(100) NOT NULL,
  LOCATION_GROUP VARCHAR2(20) NOT NULL,
  IS_ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL,
  CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_M_TRACKING_LOCATION PRIMARY KEY (LOCATION_ID),
  CONSTRAINT UK_M_TRACKING_LOCATION_CODE UNIQUE (LOCATION_CODE),
  CONSTRAINT CK_M_TRACKING_LOCATION_ACTIVE CHECK (IS_ACTIVE IN ('Y','N'))
);

CREATE TABLE M_TRACKING_PRODUCT (
  PRODUCT_ID NUMBER NOT NULL,
  PRODUCT_CODE VARCHAR2(10) NOT NULL,
  PRODUCT_NAME VARCHAR2(120) NOT NULL,
  IS_ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL,
  CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_M_TRACKING_PRODUCT PRIMARY KEY (PRODUCT_ID),
  CONSTRAINT UK_M_TRACKING_PRODUCT_CODE UNIQUE (PRODUCT_CODE),
  CONSTRAINT CK_M_TRACKING_PRODUCT_ACTIVE CHECK (IS_ACTIVE IN ('Y','N'))
);

CREATE TABLE M_TRACKING_LOCATION_PRODUCT (
  LOCATION_ID NUMBER(2) NOT NULL,
  PRODUCT_ID NUMBER NOT NULL,
  IS_ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL,
  CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_M_TRACKING_LOCATION_PRODUCT PRIMARY KEY (LOCATION_ID, PRODUCT_ID),
  CONSTRAINT FK_TRK_LP_LOCATION FOREIGN KEY (LOCATION_ID) REFERENCES M_TRACKING_LOCATION (LOCATION_ID),
  CONSTRAINT FK_TRK_LP_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES M_TRACKING_PRODUCT (PRODUCT_ID),
  CONSTRAINT CK_TRK_LP_ACTIVE CHECK (IS_ACTIVE IN ('Y','N'))
);

CREATE TABLE M_TRACKING_REQUEST
(
  REQUEST_ID NUMBER GENERATED BY DEFAULT AS IDENTITY,
  REGISTRATION_NO VARCHAR2(50) NOT NULL,
  QUEUE_NO VARCHAR2(20),
  LOCATION_ID NUMBER(2) NOT NULL,
  PRODUCT_ID NUMBER NOT NULL,
  NIK VARCHAR2(16) NOT NULL,
  APPLICANT_NAME VARCHAR2(200) NOT NULL,
  DISTRICT VARCHAR2(100),
  VILLAGE VARCHAR2(100),
  PHONE VARCHAR2(30),
  EMAIL VARCHAR2(100),
  STATUS VARCHAR2(20) DEFAULT 'BERKAS_MASUK' NOT NULL,
  SOURCE VARCHAR2(20) DEFAULT 'MANUAL' NOT NULL,
  NOTES VARCHAR2(500),
  IS_ACTIVE CHAR(1) DEFAULT 'Y' NOT NULL,
  CREATED_BY VARCHAR2(50) NOT NULL,
  CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
  UPDATED_BY VARCHAR2(50),
  UPDATED_AT DATE,
  CONSTRAINT PK_M_TRACKING_REQUEST PRIMARY KEY (REQUEST_ID),
  CONSTRAINT UK_M_TRACKING_REQUEST UNIQUE (REGISTRATION_NO),
  CONSTRAINT CK_MTR_STATUS CHECK (STATUS IN ('BERKAS_MASUK','SELESAI','DIAMBIL','BATAL')),
  CONSTRAINT CK_MTR_SOURCE CHECK (SOURCE IN ('MANUAL','SALAMAN')),
  CONSTRAINT CK_MTR_ACTIVE CHECK (IS_ACTIVE IN ('Y','N')),
  CONSTRAINT FK_MTR_LOCATION FOREIGN KEY (LOCATION_ID) REFERENCES M_TRACKING_LOCATION (LOCATION_ID),
  CONSTRAINT FK_MTR_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES M_TRACKING_PRODUCT (PRODUCT_ID)
);

CREATE INDEX IDX_MTR_NIK ON M_TRACKING_REQUEST (NIK);
CREATE INDEX IDX_MTR_STATUS ON M_TRACKING_REQUEST (STATUS);
CREATE INDEX IDX_MTR_LOCATION ON M_TRACKING_REQUEST (LOCATION_ID);
CREATE INDEX IDX_MTR_PRODUCT ON M_TRACKING_REQUEST (PRODUCT_ID);
CREATE INDEX IDX_MTR_CREATED_AT ON M_TRACKING_REQUEST (CREATED_AT);
CREATE INDEX IDX_MTR_LOCATION_STATUS ON M_TRACKING_REQUEST (LOCATION_ID, STATUS);

