// FILE: src/app/api/check/notrecord/summary/route.ts
export const runtime = "nodejs";
export const dynamic = "force-dynamic";

import { ok, err, badRequest } from "@/lib/http";
import { execRows } from "@/lib/db";
import { readServerSession } from "@/lib/session";

const ORACLE_ALIAS = process.env.DB_ALIAS_NOTRECORD ?? "DB";

export async function GET() {
  try {
    const s = await readServerSession();
    if (!s?.S_USER_ID) return badRequest("Sesi tidak valid.");

    const q2 = `
      SELECT NO_KEC,
             F5_GET_NAMA_KECAMATAN(32,73,NO_KEC) AS KECAMATAN,
             SUM(CASE WHEN KETERANGAN = 1 THEN 1 ELSE 0 END) AS SUDAH_REKAM,
             SUM(CASE WHEN KETERANGAN = 0 THEN 1 ELSE 0 END) AS BELUM_REKAM,
             COUNT(1) AS TOTAL
      FROM WKTP_BLM_REKAM_DAPODIK
      GROUP BY NO_KEC
      ORDER BY NO_KEC`;
    const q7 = `
      SELECT A.NO_KEC,
             F5_GET_NAMA_KECAMATAN(32,73,A.NO_KEC) AS KECAMATAN,
             SUM(CASE WHEN A.KETERANGAN = 1 THEN 1 ELSE 0 END) AS SUDAH_REKAM,
             SUM(CASE WHEN A.KETERANGAN = 0 THEN 1 ELSE 0 END) AS BELUM_REKAM,
             COUNT(1) AS TOTAL
      FROM WKTP_BLM_REKAM_FULL A
      WHERE NOT EXISTS (SELECT 1 FROM WKTP_BLM_REKAM_DAPODIK B WHERE A.NIK = B.NIK)
      GROUP BY A.NO_KEC
      ORDER BY A.NO_KEC`;
    const q3 = `
      SELECT UPPER(A.PROVINSI_SEKOLAH) AS PROV_SEKOLAH,
             UPPER(A.KABUPATEN_SEKOLAH) AS KAB_SEKOLAH,
             SUM(CASE WHEN KETERANGAN = 1 THEN 1 ELSE 0 END) AS SUDAH_REKAM,
             SUM(CASE WHEN KETERANGAN = 0 THEN 1 ELSE 0 END) AS BELUM_REKAM,
             COUNT(1) AS TOTAL
      FROM WKTP_BLM_REKAM_DAPODIK A
      WHERE A.KABUPATEN_SEKOLAH <> 'KOTA BANDUNG'
      GROUP BY A.PROVINSI_SEKOLAH, A.KABUPATEN_SEKOLAH
      ORDER BY A.PROVINSI_SEKOLAH, A.KABUPATEN_SEKOLAH`;
    const q4 = `
      SELECT UPPER(A.PROVINSI_SEKOLAH) AS PROV_SEKOLAH,
             UPPER(A.KABUPATEN_SEKOLAH) AS KAB_SEKOLAH,
             UPPER(A.KECAMATAN_SEKOLAH) AS KECAMATAN,
             SUM(CASE WHEN KETERANGAN = 1 THEN 1 ELSE 0 END) AS SUDAH_REKAM,
             SUM(CASE WHEN KETERANGAN = 0 THEN 1 ELSE 0 END) AS BELUM_REKAM,
             COUNT(1) AS TOTAL
      FROM WKTP_BLM_REKAM_DAPODIK A
      WHERE A.KABUPATEN_SEKOLAH = 'KOTA BANDUNG'
      GROUP BY A.PROVINSI_SEKOLAH, A.KABUPATEN_SEKOLAH, A.KECAMATAN_SEKOLAH
      ORDER BY A.PROVINSI_SEKOLAH, A.KABUPATEN_SEKOLAH, A.KECAMATAN_SEKOLAH`;
    const q5 = `
      SELECT UPPER(A.PROVINSI_SEKOLAH) AS PROV_SEKOLAH,
             UPPER(A.KABUPATEN_SEKOLAH) AS KAB_SEKOLAH,
             COALESCE(A.KECAMATAN_SEKOLAH,'-') AS KEC_SEKOLAH,
             B.NPSN AS NPSN,
             A.NAMA_SEKOLAH,
             SUM(CASE WHEN KETERANGAN = 1 THEN 1 ELSE 0 END) AS SUDAH_REKAM,
             SUM(CASE WHEN KETERANGAN = 0 THEN 1 ELSE 0 END) AS BELUM_REKAM,
             COUNT(1) AS TOTAL
      FROM WKTP_BLM_REKAM_DAPODIK A
      LEFT JOIN WKTP_KODE_SEKOLAH_DAPODIK B ON A.NAMA_SEKOLAH = B.NAMA_SEKOLAH
      WHERE A.KABUPATEN_SEKOLAH = 'KOTA BANDUNG'
      GROUP BY A.PROVINSI_SEKOLAH, A.KABUPATEN_SEKOLAH, A.KECAMATAN_SEKOLAH, A.NAMA_SEKOLAH, B.NPSN
      ORDER BY SUM(CASE WHEN KETERANGAN = 0 THEN 1 ELSE 0 END) DESC, COUNT(1) DESC`;
    const q6 = `
      SELECT UPPER(A.PROVINSI_SEKOLAH) AS PROV_SEKOLAH,
             UPPER(A.KABUPATEN_SEKOLAH) AS KAB_SEKOLAH,
             B.NPSN AS NPSN,
             A.NAMA_SEKOLAH,
             SUM(CASE WHEN KETERANGAN = 1 THEN 1 ELSE 0 END) AS SUDAH_REKAM,
             SUM(CASE WHEN KETERANGAN = 0 THEN 1 ELSE 0 END) AS BELUM_REKAM,
             COUNT(1) AS TOTAL
      FROM WKTP_BLM_REKAM_DAPODIK A
      LEFT JOIN WKTP_KODE_SEKOLAH_DAPODIK B ON A.NAMA_SEKOLAH = B.NAMA_SEKOLAH
      WHERE A.KABUPATEN_SEKOLAH <> 'KOTA BANDUNG'
      GROUP BY A.PROVINSI_SEKOLAH, A.KABUPATEN_SEKOLAH, A.KECAMATAN_SEKOLAH, A.NAMA_SEKOLAH, B.NPSN
      ORDER BY COUNT(1) DESC`;

    const [r2, r7, r3, r4, r5, r6] = await Promise.all([
      execRows(q2, {}, {}, ORACLE_ALIAS),
      execRows(q7, {}, {}, ORACLE_ALIAS),
      execRows(q3, {}, {}, ORACLE_ALIAS),
      execRows(q4, {}, {}, ORACLE_ALIAS),
      execRows(q5, {}, {}, ORACLE_ALIAS),
      execRows(q6, {}, {}, ORACLE_ALIAS),
    ]);
    return ok({ r2, r7, r3, r4, r5, r6 });
  } catch (e: any) {
    return err("Gagal memuat ringkasan", 500);
  }
}
